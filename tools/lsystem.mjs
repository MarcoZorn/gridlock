import fs from "node:fs";
import { Rng } from "../src/neat.js";
// A city grown, not drawn: streets by a branching rule in the spirit of an
// L-system. From a square in the middle four roads set out; every road
// grows a block at a time, carries on straight most of the time, and now
// and then sprouts a side street at a right angle (a little off square).
// A road stops when it reaches the edge, would cross another street, or
// comes near an existing junction, which it then joins, closing a block.
// Writes a map in the same format as tools/osm.mjs, two-way streets.
//
//   node tools/lsystem.mjs 7 > maps/grown.json
const seed = +(process.argv[2] || 7), N = +(process.env.NODES || 260), SIZE = 2000;
const rng = new Rng(seed);
const nodes = [[SIZE / 2, SIZE / 2]], edges = [];
const cross = (p, q, r, s) => {
  const d = (q[0] - p[0]) * (s[1] - r[1]) - (q[1] - p[1]) * (s[0] - r[0]);
  if (Math.abs(d) < 1e-9) return false;
  const t = ((r[0] - p[0]) * (s[1] - r[1]) - (r[1] - p[1]) * (s[0] - r[0])) / d;
  const u = ((r[0] - p[0]) * (q[1] - p[1]) - (r[1] - p[1]) * (q[0] - p[0])) / d;
  return t > 0.02 && t < 0.98 && u > 0.02 && u < 0.98;
};
// each growing tip: the junction it grows from, its heading, its rank (main roads are 0)
let tips = [0, 1, 2, 3].map((k) => ({ from: 0, a: k * Math.PI / 2 + rng.range(-0.1, 0.1), rank: 0 }));
while (tips.length && nodes.length < N) {
  const next = [];
  for (const t of tips) {
    if (nodes.length >= N) break;
    const p = nodes[t.from], len = (t.rank ? 130 : 170) * rng.range(0.8, 1.2);
    const q = [p[0] + Math.cos(t.a) * len, p[1] + Math.sin(t.a) * len];
    if (q[0] < 40 || q[1] < 40 || q[0] > SIZE - 40 || q[1] > SIZE - 40) continue;
    // near a junction already there: join it and stop
    let near = -1, best = 60;
    nodes.forEach((n, i) => { const d = Math.hypot(n[0] - q[0], n[1] - q[1]); if (i !== t.from && d < best) { best = d; near = i; } });
    const end = near >= 0 ? nodes[near] : q;
    if (edges.some(([a, b]) => a !== t.from && b !== t.from && a !== near && b !== near && cross(p, end, nodes[a], nodes[b]))) continue;
    if (near >= 0) {
      if (!edges.some(([a, b]) => (a === t.from && b === near) || (a === near && b === t.from))) edges.push([t.from, near, 1]);
      continue;
    }
    nodes.push(q);
    const id = nodes.length - 1;
    edges.push([t.from, id, 1]);
    if (rng.next() < (t.rank ? 0.85 : 0.97)) next.push({ from: id, a: t.a + rng.range(-0.12, 0.12), rank: t.rank });
    for (const side of [-1, 1]) if (rng.next() < (t.rank ? 0.3 : 0.55)) next.push({ from: id, a: t.a + side * Math.PI / 2 + rng.range(-0.15, 0.15), rank: t.rank + 1 });
  }
  tips = next.sort(() => rng.next() - 0.5);
}
// keep the largest connected piece
const adj = nodes.map(() => []);
for (const [a, b] of edges) { adj[a].push(b); adj[b].push(a); }
const comp = new Int32Array(nodes.length).fill(-1);
let biggest = -1, bigSize = 0;
for (let i = 0, k = 0; i < nodes.length; i++, k++) {
  if (comp[i] >= 0) continue;
  const stack = [i]; comp[i] = k; let size = 0;
  while (stack.length) { const v = stack.pop(); size++; for (const w of adj[v]) if (comp[w] < 0) { comp[w] = k; stack.push(w); } }
  if (size > bigSize) { bigSize = size; biggest = k; }
}
const keep = [], index = new Map();
nodes.forEach((n, i) => { if (comp[i] === biggest) { index.set(i, keep.length); keep.push(n.map(Math.round)); } });
const out = { name: `Grown city, seed ${seed}`, attribution: "generated by tools/lsystem.mjs", nodes: keep, edges: edges.filter(([a, b]) => index.has(a) && index.has(b)).map(([a, b, l]) => [index.get(a), index.get(b), l]) };
console.error(`${out.nodes.length} junctions, ${out.edges.length} streets`);
process.stdout.write(JSON.stringify(out));
