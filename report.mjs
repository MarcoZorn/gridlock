// Turns every runs/*/telemetry.jsonl into LIVE.md: a table comparing the
// runs over their latest generations, and one small SVG chart per metric.
//
//   node report.mjs            # writes LIVE.md and docs/live-*.svg
import fs from "node:fs";
import path from "node:path";

const WINDOW = 100;     // generations averaged for the table
const SMOOTH = 25;      // rolling mean for the charts

const runs = fs.readdirSync("runs", { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join("runs", d.name, "telemetry.jsonl")))
  .map((d) => {
    const rows = fs.readFileSync(path.join("runs", d.name, "telemetry.jsonl"), "utf8")
      .split("\n").filter(Boolean).map((l) => JSON.parse(l));
    return { name: d.name, rows };
  })
  .filter((r) => r.rows.length)
  .sort((a, b) => a.name.localeCompare(b.name));

if (!runs.length) { console.log("no runs with telemetry"); process.exit(0); }

const POP = 120;
const METRICS = [
  ["trips / car / min", (r) => r.throughput],
  ["crashes / km", (r) => r.crashesPerKm],
  ["car-on-car crashes / car", (r) => r.carCrashes / POP],
  ["mean trip time (s)", (r) => r.tripTime],
  ["waiting in junctions (%)", (r) => r.waitShare * 100],
  ["keeps to (right +)", (r) => r.side],
  ["red lights run / car", (r) => (r.control === "lights" ? r.redRuns / POP : null)],
];

const mean = (xs) => {
  const v = xs.filter((x) => x !== null && Number.isFinite(x));
  return v.length ? v.reduce((a, b) => a + b, 0) / v.length : null;
};
const fmt = (x) => (x === null ? "-" : Math.abs(x) >= 100 ? x.toFixed(0) : x.toFixed(2));

// Table: the latest WINDOW generations of each run, traffic generations only
// where a run has any, since ghost generations are a different experiment.
let md = `# Live runs\n\nGenerated by \`node report.mjs\` from \`runs/*/telemetry.jsonl\`. `;
md += `Each column is the mean over a run's latest ${WINDOW} generations in traffic.\n\n`;
md += `| | ${runs.map((r) => r.name).join(" | ")} |\n|---|${runs.map(() => "---").join("|")}|\n`;
md += `| generation | ${runs.map((r) => r.rows.at(-1).gen).join(" | ")} |\n`;
const windows = runs.map((r) => {
  const t = r.rows.filter((x) => x.traffic);
  return (t.length ? t : r.rows).slice(-WINDOW);
});
for (const [label, f] of METRICS) {
  md += `| ${label} | ${windows.map((w) => fmt(mean(w.map(f)))).join(" | ")} |\n`;
}
md += `\n`;

// Charts: one per metric, every run as one line, rolling mean.
const COLORS = ["#ff8a5c", "#6ea8ff", "#5ac8a0", "#e8c46a", "#8b7cf6", "#e86e64"];
fs.mkdirSync("docs", { recursive: true });
METRICS.forEach(([label, f], mi) => {
  const W = 200 + 110 * runs.length + 60, H = 200, P = 34;
  const series = runs.map((r) => {
    const raw = r.rows.map((x) => [x.gen, f(x)]).filter(([, y]) => y !== null && Number.isFinite(y));
    return raw.map(([g], i) => [g, mean(raw.slice(Math.max(0, i - SMOOTH + 1), i + 1).map(([, y]) => y))]);
  });
  const all = series.flat();
  if (!all.length) return;
  const gx = Math.max(...all.map(([g]) => g)) || 1;
  let y0 = Math.min(0, ...all.map(([, y]) => y)), y1 = Math.max(...all.map(([, y]) => y));
  if (y1 === y0) y1 = y0 + 1;
  const X = (g) => P + (g / gx) * (W - P - 10), Y = (y) => H - P + 10 - ((y - y0) / (y1 - y0)) * (H - P - 10);
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" font-family="monospace" font-size="10">`;
  svg += `<rect width="${W}" height="${H}" fill="#14161c"/>`;
  svg += `<text x="${P}" y="14" fill="#e6e8ee">${label}</text>`;
  svg += `<text x="4" y="${Y(y1) + 4}" fill="#8b93a7">${fmt(y1)}</text><text x="4" y="${Y(y0) + 4}" fill="#8b93a7">${fmt(y0)}</text>`;
  svg += `<text x="${W - 60}" y="${H - 6}" fill="#8b93a7">gen ${gx}</text>`;
  if (y0 < 0) svg += `<line x1="${P}" x2="${W - 10}" y1="${Y(0)}" y2="${Y(0)}" stroke="#232733"/>`;
  series.forEach((s, i) => {
    if (s.length < 2) return;
    svg += `<polyline fill="none" stroke="${COLORS[i % COLORS.length]}" stroke-width="1.5" points="${s.map(([g, y]) => `${X(g).toFixed(1)},${Y(y).toFixed(1)}`).join(" ")}"/>`;
    svg += `<text x="${P + 200 + i * 110}" y="14" fill="${COLORS[i % COLORS.length]}">${runs[i].name}</text>`;
  });
  svg += `</svg>\n`;
  const file = `docs/live-${mi}.svg`;
  fs.writeFileSync(file, svg);
  md += `![${label}](${file})\n\n`;
});

fs.writeFileSync("LIVE.md", md);
console.log(`LIVE.md: ${runs.length} runs`);
